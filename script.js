function renderStories() {
  const visible = articles.filter(article => {
    const categoryMatch = activeCategory === "All" || article.category === activeCategory;
    const searchable = `${article.title} ${article.category} ${article.deck} ${article.excerpt}`.toLowerCase();
    return categoryMatch && searchable.includes(activeQuery.toLowerCase().trim());
  });
  grid.innerHTML = visible.map(article => `
    <article class="story-card" tabindex="0" role="link" aria-label="Read ${escapeHTML(article.title)}" data-open-article="${article.id}">
      ${artMarkup(article, Number(article.number))}
      <div class="story-card-copy">
        <div class="article-meta"><span>${escapeHTML(article.category.toUpperCase())}</span><span>${escapeHTML(article.read)}</span></div>
        <h3>${escapeHTML(article.title)}</h3>
        <p>${escapeHTML(article.excerpt)}</p>
        <div class="story-card-footer"><span>ISSUE 001 / ${escapeHTML(article.number.padStart(2,"0"))}</span><span aria-hidden="true">↗</span></div>
      </div>
    </article>`).join("");
  emptyState.hidden = visible.length > 0;
  storyCount.textContent = `${String(visible.length).padStart(2,"0")} ${visible.length === 1 ? "STORY" : "STORIES"}`;
  document.querySelectorAll(".filter-chip").forEach(button => {
    const active = button.dataset.category === activeCategory;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
    const categoryCount = articles.filter(a => button.dataset.category === "All" || a.category === button.dataset.category).length;
    const existingCount = button.querySelector("span");
    if (button.dataset.category === "All") {
      if (existingCount) existingCount.textContent = String(categoryCount).padStart(2,"0");
      else button.insertAdjacentHTML("beforeend", `<span>${String(categoryCount).padStart(2,"0")}</span>`);
    }
  });
  document.querySelectorAll(".nav-link").forEach(button => {
    button.classList.toggle("active", button.dataset.category === activeCategory);
    button.setAttribute("aria-pressed", String(button.dataset.category === activeCategory));
  });
  if (searchPanel.hidden === false) {
    searchStatus.textContent = activeQuery ? `${visible.length} RESULT${visible.length === 1 ? "" : "S"} FOR “${activeQuery.toUpperCase()}”.` : "SEARCH BY TITLE, CATEGORY, OR KEYWORD.";
  }
}
function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove("show"), 3000);
}
function renderArticle(article) {
  const paragraphs = article.paragraphs.map(([type, text]) => {
    if (type === "h2") return `<h2>${escapeHTML(text)}</h2>`;
    if (type === "quote") return `<blockquote>${escapeHTML(text)}</blockquote>`;
    if (type === "callout") return `<div class="article-callout">${escapeHTML(text)}</div>`;
    return `<p>${escapeHTML(text)}</p>`;
  }).join("");
  const index = articles.findIndex(a => a.id === article.id);
  currentArticleIndex = index;
  articleContent.innerHTML = `
    <div class="article-body">
      <div class="article-kicker"><span>${escapeHTML(article.category.toUpperCase())}</span><span>ISSUE 001 / ${article.number}</span></div>
      <h1 class="article-title">${escapeHTML(article.title)}</h1>
      <p class="article-deck">${escapeHTML(article.deck)}</p>
      <div class="article-byline"><span>WORDS BY THE INTERNET DEPT.</span><span>${escapeHTML(article.date)} · ${escapeHTML(article.read)}</span></div>
      <div class="article-hero-art ${article.id === "algorithmic-taste" ? "art-mono" : article.id === "small-tools" ? "art-tech" : article.id === "creative-routine" ? "art-poster" : article.id === "tabs-open" ? "art-life" : article.id === "personal-web" ? "art-pixel" : article.id === "designing-for-feeling" ? "art-design" : "art-culture"}">${article.id === "personal-web" ? '<div class="pixel-grid" aria-hidden="true">'+Array.from({length:49},(_,i)=>`<i style="opacity:${[0,1,2,6,7,13,20,21,27,28,34,35,41,42,43,48].includes(i)?".18":"1"}"></i>`).join("")+'</div>' : `<div class="art-type">${article.artText || "MY<br>HOMEPAGE"}</div>`}</div>
      <div class="article-content">${paragraphs}</div>
    </div>`;
  document.querySelector("#article-issue").textContent = `THE INTERNET DEPT. / STORY ${article.number} OF 08`;
  mainContent.hidden = true;
  articleView.hidden = false;
  searchPanel.hidden = true;
  document.body.classList.remove("no-scroll");
  window.scrollTo({top:0,behavior:"instant"});
  history.replaceState({article:article.id}, "", `#story-${article.id}`);
  document.title = `${article.title} — THE INTERNET DEPT.`;
}
function openArticle(id) {
  const article = articles.find(item => item.id === id);
  if (article) renderArticle(article);
}
